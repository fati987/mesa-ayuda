-- Esquema completo del dominio. Solo Ticket, Contacto, Llamada, Area, Usuario,
-- Categoria y HistorialEstado tienen entidad JPA en Sprint 1; el resto de las
-- tablas existen desde ya para que las migraciones futuras solo agreguen
-- columnas o datos, nunca la estructura base.

-- =========================================================================
-- area
-- =========================================================================
create table area (
    id                  bigint generated by default as identity primary key,
    nombre              varchar(100)  not null,
    recibe_llamadas     boolean       not null default false,
    limite_wip_agente   integer       not null default 5,
    activo              boolean       not null default true,
    creado_en           timestamptz   not null default now(),
    actualizado_en      timestamptz   not null default now(),
    creado_por          varchar(100)  not null,
    actualizado_por     varchar(100)  not null,
    version             bigint        not null default 0,
    constraint uq_area_nombre unique (nombre),
    constraint chk_area_limite_wip check (limite_wip_agente > 0)
);

-- =========================================================================
-- usuario
-- =========================================================================
create table usuario (
    id                  bigint generated by default as identity primary key,
    nombre_completo     varchar(150)  not null,
    correo              varchar(150)  not null,
    rol                 varchar(20)   not null,
    area_id             bigint        not null references area(id),
    activo              boolean       not null default true,
    creado_en           timestamptz   not null default now(),
    actualizado_en      timestamptz   not null default now(),
    creado_por          varchar(100)  not null,
    actualizado_por     varchar(100)  not null,
    version             bigint        not null default 0,
    constraint uq_usuario_correo unique (correo),
    constraint chk_usuario_rol check (rol in ('AGENTE', 'SUPERVISOR', 'ADMIN'))
);

create index idx_usuario_area_id on usuario (area_id);
create index idx_usuario_rol on usuario (rol);

-- =========================================================================
-- contacto (cliente, sin credenciales)
-- =========================================================================
create table contacto (
    id                  bigint generated by default as identity primary key,
    nombre_completo     varchar(150)  not null,
    telefono            varchar(30)   not null,
    correo              varchar(150),
    activo              boolean       not null default true,
    creado_en           timestamptz   not null default now(),
    actualizado_en      timestamptz   not null default now(),
    creado_por          varchar(100)  not null,
    actualizado_por     varchar(100)  not null,
    version             bigint        not null default 0
);

create index idx_contacto_telefono on contacto (telefono);

-- =========================================================================
