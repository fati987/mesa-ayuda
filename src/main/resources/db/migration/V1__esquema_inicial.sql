    constraint uq_columna_tablero_area_orden unique (area_id, orden),
    constraint chk_columna_tablero_orden check (orden >= 0),
    constraint chk_columna_tablero_estado check (estado_asociado in ('NUEVO', 'DERIVADO', 'EN_PROGRESO', 'ESPERANDO_CLIENTE', 'RESUELTO', 'CERRADO'))
);

-- =========================================================================
-- ticket_etiqueta (unión N:M)
-- =========================================================================
create table ticket_etiqueta (
    ticket_id       bigint        not null references ticket(id),
    etiqueta_id     bigint        not null references etiqueta(id),
    creado_en       timestamptz   not null default now(),
    primary key (ticket_id, etiqueta_id)
);
